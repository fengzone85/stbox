#!/usr/bin/env bash
# 构建单文件发布产物：stbox.sh + stbox.sh.sha256
# 用法：bash build.sh [--check]
#   --check  只校验现有产物是否与源码一致，不覆盖

set -euo pipefail

SST_HOME=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)
cd "$SST_HOME"
export LC_ALL=C

OUT="$SST_HOME/stbox.sh"
SHA_FILE="$SST_HOME/stbox.sh.sha256"
CHECK=0
case ${1:-} in
  --check) CHECK=1 ;;
  '') ;;
  -h|--help)
    printf '用法：bash build.sh [--check]\n'
    exit 0
    ;;
  *) printf '未知参数：%s\n' "$1" >&2; exit 1 ;;
esac

VERSION=$(cat "$SST_HOME/VERSION")
TMP=$(mktemp)
trap 'rm -f "$TMP"' EXIT

emit_file() {
  local file=$1
  printf '\n# --- %s ---\n' "$file"
  sed '1{/^#!/d;}' "$file"
}

{
  printf '%s\n' '#!/usr/bin/env bash' \
    '# STBOX single-file bundle (generated by build.sh)' \
    'SST_BUNDLED=1' \
    "SST_VERSION=\"$VERSION\""
  tail -n +2 "$SST_HOME/st.sh" | awk '/^# --- bundle:core ---$/ {exit} {print}'
  printf '\n'

  for file in core/ui.sh core/common.sh core/config.sh core/wizard.sh core/apps.sh core/scripts.sh core/update.sh core/menu.sh; do
    emit_file "$file"
  done

  for file in modules/*.sh; do
    emit_file "$file"
  done

  for dir in apps/*/; do
    name=$(basename "$dir")
    [[ -f ${dir}app.conf ]] || continue
    printf '\n# --- app: %s ---\n' "$name"
    cat "${dir}app.conf"
    printf '\n'
    printf "SST_APP_TITLE['%s']=\$APP_TITLE\n" "$name"
    printf "SST_APP_DESC['%s']=\$APP_DESC\n" "$name"
    printf "SST_APP_CATEGORY['%s']=\$APP_CATEGORY\n" "$name"
    printf "SST_APP_PORT['%s']=\$APP_PORT\n" "$name"
    printf "SST_APP_URL['%s']=\$APP_URL\n" "$name"
    printf "SST_APP_DIR['%s']=''\n" "$name"
    printf "SST_APP_ORDER+=('%s')\n" "$name"
    [[ -f ${dir}app.sh ]] && emit_file "${dir}app.sh"
  done

  for conf in scripts/*.conf; do
    name=$(basename "$conf" .conf)
    bash -c '
      SCRIPT_TITLE=""
      SCRIPT_DESC=""
      SCRIPT_CATEGORY=""
      SCRIPT_URL=""
      SCRIPT_MODE=""
      SCRIPT_ARG=""
      SCRIPT_ROOT=""
      SCRIPT_RISK=""
      SCRIPT_SHA256=""
      SCRIPT_ARCH=""
      source "$1"
      printf "SST_SCRIPT_TITLE[%q]=%q\n" "$2" "${SCRIPT_TITLE:-}"
      printf "SST_SCRIPT_DESC[%q]=%q\n" "$2" "${SCRIPT_DESC:-}"
      printf "SST_SCRIPT_CATEGORY[%q]=%q\n" "$2" "${SCRIPT_CATEGORY:-}"
      printf "SST_SCRIPT_URL[%q]=%q\n" "$2" "${SCRIPT_URL:-}"
      printf "SST_SCRIPT_MODE[%q]=%q\n" "$2" "${SCRIPT_MODE:-bash}"
      printf "SST_SCRIPT_ARG[%q]=%q\n" "$2" "${SCRIPT_ARG:-}"
      printf "SST_SCRIPT_ROOT[%q]=%q\n" "$2" "${SCRIPT_ROOT:-1}"
      printf "SST_SCRIPT_RISK[%q]=%q\n" "$2" "${SCRIPT_RISK:-中}"
      printf "SST_SCRIPT_SHA256[%q]=%q\n" "$2" "${SCRIPT_SHA256:-}"
      printf "SST_SCRIPT_ARCH[%q]=%q\n" "$2" "${SCRIPT_ARCH:-}"
    ' _ "$conf" "$name"
    printf "SST_SCRIPT_ORDER+=('%s')\n" "$name"
  done

  cat <<'FUNC'

# --- SSH 回滚脚本（单文件模式写入状态目录） ---
stbox_write_ssh_rollback() {
  local dir=${SST_STATE_DIR:-}
  [[ -n $dir ]] || return 1
  mkdir -p "$dir" || return 1
  cat >"$dir/ssh-rollback.sh" <<'STBOX_ROLLBACK'
FUNC
  cat "$SST_HOME/core/ssh-rollback.sh"
  cat <<'FUNC'
STBOX_ROLLBACK
  chmod 700 "$dir/ssh-rollback.sh" 2>/dev/null || true
}
FUNC

  awk 'found {print} /^# --- bundle:entry ---$/ {found=1}' "$SST_HOME/st.sh"
} >"$TMP"

if (( CHECK )); then
  if ! cmp -s "$TMP" "$OUT"; then
    printf 'stbox.sh 与源码不一致，请先执行：bash build.sh\n' >&2
    exit 1
  fi
  expected=$(sha256sum "$OUT" | awk '{print $1}')
  current=$(awk 'NR==1 {print $1}' "$SHA_FILE" 2>/dev/null || true)
  if [[ $expected != "$current" ]]; then
    printf 'stbox.sh.sha256 校验值不一致，请先执行：bash build.sh\n' >&2
    exit 1
  fi
  printf '单文件产物已是最新。\n'
  exit 0
fi

if ! install -m 755 "$TMP" "$OUT" 2>/dev/null; then
  cat "$TMP" >"$OUT" || {
    printf '写入产物失败：%s\n' "$OUT" >&2
    exit 1
  }
  chmod 755 "$OUT" || true
fi
rm -f "$TMP"
( cd "$SST_HOME" && sha256sum stbox.sh ) >"$SHA_FILE"
trap - EXIT
printf '已生成 %s\n校验文件 %s\n' "$OUT" "$SHA_FILE"
